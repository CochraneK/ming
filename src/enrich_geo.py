geo = json.load(open(GEO, encoding="utf-8"))
geo_keys = {g["ancient"] for g in geo}
data = json.load(open(DATA, encoding="utf-8"))

added_coords = 0
added_type = 0
already = 0
for l in data["locations"]:
    has_coord = l.get("lng") is not None and l.get("lat") is not None
    if has_coord:
        continue
    a = l["ancient"]
    entry = None
    for g in geo:
        if g["ancient"] == a:
            entry = g
            break
    if entry is None:
        # 新建条目
        t = GAZ.get(a, (None, None, None, rule_type(a)))
        lng, lat, modern, ttype = t[0], t[1], t[2], t[3]
        new = {"ancient": a, "trace_type": ttype, "status": "抽取待补"}
        if lng is not None:
            new["lng"] = lng
            new["lat"] = lat
            new["modern_address"] = modern
            new["status"] = "坐标来自内置地名词典（待核验）"
            added_coords += 1
        else:
            added_type += 1
        geo.append(new)
    else:
        # 已有条目但缺坐标/类型
        if "trace_type" not in entry or not entry.get("trace_type"):
            ttype = GAZ.get(a, (None, None, None, rule_type(a)))[3]
            if ttype:
                entry["trace_type"] = ttype
                added_type += 1
        if entry.get("lng") is None and a in GAZ:
            lng, lat, modern, _ = GAZ[a]
            if lng is not None:
                entry["lng"] = lng
                entry["lat"] = lat
                entry["modern_address"] = modern
                entry["status"] = "坐标来自内置地名词典（待核验）"
                added_coords += 1

# ---- 受控词表归一：把历史遗留零散类型并入 8 类，保持圣地巡礼分类一致 ----
CONTROLLED = {"地名","古战场","遗址·陵","关隘","祠堂","故居·出生地","起航地","纪念碑"}
NORM = {
    "城市":"地名","航海停靠":"起航地","航海":"起航地","宫殿":"地名","其他遗址":"地名",
    "坛庙":"祠堂","书院":"祠堂","寺观":"祠堂","古城址":"地名","海岛":"地名",
    "山川":"地名","地名典故":"地名","河流":"地名","故居/出生地":"故居·出生地","关":"关隘",
    "遗址/陵":"遗址·陵",
}
normed = 0
for g in geo:
    t = g.get("trace_type")
    if t == "manual":  # 早期占位类型，按名称规则重判
        g["trace_type"] = rule_type(g["ancient"])
        normed += 1
    elif t and t not in CONTROLLED and t in NORM:
        g["trace_type"] = NORM[t]
        normed += 1
# 兜底：任何不在 8 类受控词表内的类型强制归为 地名
for g in geo:
    if g.get("trace_type") not in CONTROLLED:
        g["trace_type"] = "地名"

json.dump(geo, open(GEO, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
