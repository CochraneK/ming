# ---- 规则分类器：名称关键词 -> trace_type（8 类受控词表）----
def rule_type(name):
    n = name
    if re.search(r"陵|墓|坟|孝陵|长陵|十三陵|皇陵|福陵|昭陵|庆陵|德陵|思陵|定陵|显陵", n):
        return "遗址·陵"
    if re.search(r"祠|庙|岳王|关帝|文庙|武庙|太庙", n):
        return "祠堂"
    if re.search(r"关", n):
        return "关隘"
    if re.search(r"寺|观|庵", n):
        return "其他遗址"
    if re.search(r"宫|殿|阁|楼|门|桥|府|堂|院|城$|卫$|所$|堡$|营$|寨$|庵$", n):
        return "其他遗址"
    if re.search(r"卫|所|堡|营|寨|镇", n):
        return "古战场"
    if re.search(r"江|河|湖|海|川|水|溪|浦|津|峡|渡|口", n):
        return "地名"
    if re.search(r"山|岭|峰|岗|原|川|平原", n):
        return "地名"
    return "地名"

