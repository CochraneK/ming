# 箭头符号清洗：抽取文本里偶发的箭头字符统一转为可读中文连接词，
# 保证报告任何展示路径都不会出现奇怪符号。
ARROW_CHARS = "→⇢⇒➜➝➞←↔"


def clean_arrows(text, sep="，"):
    if not text:
        return text
    for arrow in ARROW_CHARS:
        text = text.replace(arrow, sep)
    return text


def clean_location_route(text):
    """行军路线类地点：按箭头拆段，逐段归一古地名，再以顿号连接。"""
    if not text or not any(arrow in text for arrow in ARROW_CHARS):
        return LOCATION_CANON.get(text, text) if text else text
    parts = []
    current = text
    for arrow in ARROW_CHARS:
        current = current.replace(arrow, "|")
    for segment in current.split("|"):
        segment = segment.strip()
        if segment:
            parts.append(LOCATION_CANON.get(segment, segment))
    return "、".join(parts) if parts else text
